defmodule Flezha.ChildSpecTest do
  @moduledoc """
  The supervision contract of every controller worker whose `child_spec/1` is
  generated by `use GenServer, <option>` rather than hand-written: the option is
  pinned here, and the keys the generated map omits are proved invisible to OTP.
  """

  use ExUnit.Case, async: true

  # Each worker and the one supervision option it declares. A wrong option, or
  # one lost in a later edit, is red on the next run.
  @workers [
    {Flezha.AuthZ.SourceRegistration, %{restart: :transient}},
    {Flezha.AuthZ.Bootstrap.OnBoot, %{restart: :transient}},
    {Flezha.Shutdown.SignalHandler, %{shutdown: 5_000}},
    {Flezha.Shutdown.Coordinator, %{shutdown: 30_000}},
    {Flezha.Healthz.Server, %{}}
  ]

  defmodule Standin do
    @moduledoc false
    def start_link(_opts), do: Agent.start_link(fn -> :ok end)
  end

  for {module, option} <- @workers do
    test "#{inspect(module)} declares #{inspect(option)} and nothing more" do
      module = unquote(module)

      assert module.child_spec([]) ==
               Map.merge(
                 %{id: module, start: {module, :start_link, [[]]}},
                 unquote(Macro.escape(option))
               )
    end
  end

  # `use GenServer, <option>` emits neither `type: :worker` nor `restart: :permanent`,
  # where a hand-written map may state both. This is what makes dropping them safe:
  # the spec OTP ends up holding is the same either way. Asserted against a live
  # supervisor rather than read from the documentation.
  for {option, stated} <- [
        {%{restart: :transient}, %{type: :worker}},
        {%{shutdown: 5_000}, %{type: :worker}},
        {%{shutdown: 30_000}, %{type: :worker}},
        {%{}, %{type: :worker, restart: :permanent}}
      ] do
    test "stating #{inspect(Map.keys(stated))} beside #{inspect(option)} changes nothing OTP can see" do
      base = %{id: Standin, start: {Standin, :start_link, [[]]}}
      lean = Map.merge(base, unquote(Macro.escape(option)))
      verbose = Map.merge(lean, unquote(Macro.escape(stated)))

      assert normalise(lean) == normalise(verbose)
    end
  end

  defp normalise(spec) do
    {:ok, sup} = Supervisor.start_link([spec], strategy: :one_for_one)
    on_exit(fn -> if Process.alive?(sup), do: Supervisor.stop(sup) end)
    {:ok, normalised} = :supervisor.get_childspec(sup, Standin)
    Supervisor.stop(sup)
    normalised
  end
end
